#!/usr/bin/env python3
"""Cluster glyph samples (agr-tool omr train -> TSV) into per-label centroids and emit
Core/Sources/AGRCore/OMR/GlyphTemplates.generated.swift.

usage: train_glyphs.py samples.tsv OUT.swift [--k 10] [--eval]
"""
import sys, collections
import numpy as np

def load(path):
    X, A, Y = [], [], []
    for line in open(path, encoding="utf-8"):
        p = line.rstrip("\n").split("\t")
        if len(p) < 3: continue
        Y.append(p[0]); X.append(np.frombuffer(bytes.fromhex(p[1]), dtype=np.uint8)); A.append(int(p[2]))
    return np.array(X, dtype=np.float32), np.array(A, dtype=np.float32), np.array(Y)

def kmeans(X, A, k, iters=15, seed=1):
    rng = np.random.RandomState(seed)
    n = len(X)
    k = min(k, n)
    idx = rng.choice(n, k, replace=False)
    C, CA = X[idx].copy(), A[idx].copy()
    for _ in range(iters):
        d = np.abs(X[:, None, :] - C[None]).sum(2) / (X.shape[1] * 255) + 0.35 * np.abs(A[:, None] - CA[None]) / 100
        lab = d.argmin(1)
        for j in range(k):
            m = lab == j
            if m.any(): C[j] = X[m].mean(0); CA[j] = A[m].mean()
    return C, CA

def classify(C, CA, CL, x, a):
    d = np.abs(C - x).sum(1) / (len(x) * 255) + 0.35 * np.abs(CA - a) / 100
    return CL[d.argmin()]

def main():
    path, out = sys.argv[1], sys.argv[2]
    k = int(sys.argv[sys.argv.index("--k") + 1]) if "--k" in sys.argv else 10
    X, A, Y = load(path)
    print(len(X), collections.Counter(Y).most_common(20))
    def fit(X, A, Y):
        C, CA, CL = [], [], []
        for lab in sorted(set(Y)):
            m = Y == lab
            if m.sum() < 3: continue
            c, ca = kmeans(X[m], A[m], k)
            C.append(c); CA.append(ca); CL += [lab] * len(c)
        return np.vstack(C), np.concatenate(CA), np.array(CL)
    if "--eval" in sys.argv:
        rng = np.random.RandomState(7)
        perm = rng.permutation(len(X)); cut = int(len(X) * 0.8)
        tr, te = perm[:cut], perm[cut:]
        C, CA, CL = fit(X[tr], A[tr], Y[tr])
        ok = sum(classify(C, CA, CL, X[i], A[i]) == Y[i] for i in te)
        print("holdout acc", ok / len(te))
        wrong = collections.Counter((Y[i], classify(C, CA, CL, X[i], A[i])) for i in te if classify(C, CA, CL, X[i], A[i]) != Y[i])
        print(wrong.most_common(12))
    C, CA, CL = fit(X, A, Y)
    with open(out, "w") as f:
        f.write("// Generated by tools/ocr/train_glyphs.py -- do not edit.\n")
        f.write("// %d centroids over %d samples (12x16 area-resampled glyph bitmaps + aspect).\n" % (len(CL), len(X)))
        f.write("enum OMRGlyphTemplates {\n    static let data: [String] = [\n")
        for c, ca, l in zip(C, CA, CL):
            f.write('        "%s:%s:%d",\n' % (l, bytes(np.clip(c, 0, 255).astype(np.uint8)).hex(), int(ca)))
        f.write("    ]\n    static func load() -> [OMRGlyphTemplate] {\n")
        f.write("        data.compactMap { s in\n            let p = s.split(separator: \":\", omittingEmptySubsequences: false)\n            guard p.count == 3 else { return nil }\n")
        f.write("            var v = [UInt8](); v.reserveCapacity(192)\n            var it = p[1].makeIterator()\n            while let a = it.next(), let b = it.next() { v.append(UInt8(String([a, b]), radix: 16) ?? 0) }\n")
        f.write("            return OMRGlyphTemplate(label: String(p[0]), v: v, aspect: Int(p[2]) ?? 100)\n        }\n    }\n}\n")
main()
